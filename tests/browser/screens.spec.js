import { test, expect } from '@playwright/test';
const key = 'nawras-this-or-that:leaderboard:v1';
const records = () => Array.from({length:25}, (_,i) => ({playerId:`p${i}`, resultId:`r${i}`, name:i===0?'<img src=x onerror=alert(1)>':`Player ${i}`, score:i<4?100-i*10:60, answerTimeMs:i===5?1040:1000+i*10}));
test('landing, name entry, empty leaderboard and base assets', async ({page}) => {
  const errors=[]; page.on('pageerror', error=>errors.push(error.message));
  await page.goto('./');
  await expect(page.getByRole('button',{name:'Start',exact:true})).toBeDisabled();
  await page.getByRole('textbox',{name:'Player name'}).fill('  Nawras  ');
  await page.getByRole('button',{name:'Leaderboard',exact:true}).click();
  await expect(page.getByText('No completed rounds yet.')).toBeVisible();
  await expect(page.getByRole('button',{name:'Clear Leaderboard'})).toBeDisabled();
  await expect(page.getByRole('columnheader')).toHaveText(['Rank','Player','Score','Answer Time']);
  await page.getByRole('button',{name:'← Back'}).click();
  await expect(page.getByRole('textbox')).toHaveValue('Nawras');
  await expect(page.getByRole('button',{name:'Start',exact:true})).toBeEnabled();
  const assets=await page.evaluate(()=> [...document.images].map(img=>({src:img.src,valid:img.complete && img.naturalWidth>0})));
  expect(assets.every(img=>img.valid && img.src.includes('/nawras-this-or-that/assets/'))).toBeTruthy();
  expect((await page.request.get('assets/pixel-particles.png')).ok()).toBeTruthy();
  await page.screenshot({path:'test-results/landing.png'});
  expect(errors).toEqual([]);
});
test('persistence, safe names, tied top five, sticky headings and confirmation', async ({page}) => {
  await page.goto('./');
  await page.evaluate(({key,records})=>{localStorage.setItem(key,JSON.stringify({version:1,results:records}));localStorage.setItem('other-game','keep');},{key,records:records()});
  await page.reload();
  await page.getByRole('button',{name:'Leaderboard',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(25);
  await expect(page.locator('.rank-5')).toHaveCount(2);
  await expect(page.locator('tbody img')).toHaveCount(0);
  await expect(page.locator('tbody tr').first()).toContainText('<img src=x onerror=alert(1)>');
  const panel=page.locator('.leaderboard-panel');
  await panel.evaluate(el=>{el.scrollTop=300;});
  await expect(page.getByRole('columnheader',{name:'Rank',exact:true})).toBeInViewport();
  const before=await panel.boundingBox(); const scroll=await panel.evaluate(el=>el.scrollTop);
  await page.getByRole('button',{name:'Clear Leaderboard'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('button',{name:'Cancel',exact:true})).toBeFocused();
  expect(await panel.boundingBox()).toEqual(before);
  await page.keyboard.press('Tab'); await expect(page.getByRole('button',{name:'Clear',exact:true})).toBeFocused();
  await page.keyboard.press('Tab'); await expect(page.getByRole('button',{name:'Close clear popup'})).toBeFocused();
  await page.keyboard.press('Tab'); await expect(page.getByRole('button',{name:'Cancel',exact:true})).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  expect(await panel.evaluate(el=>el.scrollTop)).toEqual(scroll);
  await page.getByRole('button',{name:'Clear Leaderboard'}).click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(25);
  await page.screenshot({path:'test-results/leaderboard.png'});
  await page.getByRole('button',{name:'Clear Leaderboard'}).click();
  await page.screenshot({path:'test-results/confirmation.png'});
  await page.getByRole('button',{name:'Clear',exact:true}).click();
  await expect(page.getByText('No completed rounds yet.')).toBeVisible();
  expect(await page.evaluate(()=>localStorage.getItem('other-game'))).toBe('keep');
  expect(await page.evaluate(key=>localStorage.getItem(key),key)).toBeNull();
  await page.reload(); await page.getByRole('button',{name:'Leaderboard',exact:true}).click();
  await expect(page.getByRole('button',{name:'Clear Leaderboard'})).toBeDisabled();
});
test('small screen, reduced motion, malformed data, fullscreen typing guard', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:'reduce'}); await page.goto('./');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  expect(await page.locator('.particles i').first().evaluate(el=>getComputedStyle(el).animationName)).toBe('none');
  await page.getByRole('textbox').fill(''); await page.keyboard.press('f');
  await expect(page.getByRole('textbox')).toHaveValue('f');
  expect(await page.evaluate(()=>!!document.fullscreenElement)).toBeFalsy();
  await page.getByRole('button',{name:'Leaderboard',exact:true}).click();
  await page.keyboard.press('f');
  await expect.poll(() => page.evaluate(() => !!document.fullscreenElement)).toBe(true);
  await page.keyboard.press('f');
  await expect.poll(() => page.evaluate(() => !!document.fullscreenElement)).toBe(false);
  await page.evaluate(key=>localStorage.setItem(key,'broken'),key); await page.reload();
  await page.getByRole('button',{name:'Leaderboard',exact:true}).click();
  await expect(page.getByText('Saved leaderboard could not be read.')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:'test-results/mobile.png'});
});
